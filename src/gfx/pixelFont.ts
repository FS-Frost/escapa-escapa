// Accented letters: base glyph + diacritic pixels [col, row] (row < 0 = above cap).
const ACUTE: [number, number][] = [[3, -3], [2, -2]];
const DIACRITICS: Record<string, [string, [number, number][]]> = {
  'Á': ['A', ACUTE], 'É': ['E', ACUTE], 'Í': ['I', [[2, -3], [1, -2]]], 'Ó': ['O', ACUTE], 'Ú': ['U', ACUTE],
  'Ñ': ['N', [[1, -2], [2, -3], [3, -2], [4, -3]]],
  'Ü': ['U', [[1, -2], [3, -2]]],
};

export interface Glyph { w: number; runs: [number, number, number][]; } // runs: x, y, len

function build(rows: string[], extra: [number, number][] = []): Glyph {
  const runs: [number, number, number][] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (row[x] === '#') x++;
      runs.push([start, y, x - start]);
    }
  });
  for (const [x, y] of extra) runs.push([x, y, 1]);
  return { w: rows[0].length, runs };
}

const glyphs = new Map<string, Glyph>();
for (const [ch, def] of Object.entries(G)) glyphs.set(ch, build(def.split('|')));
for (const [ch, [base, marks]] of Object.entries(DIACRITICS)) glyphs.set(ch, build(G[base].split('|'), marks));

export function glyph(ch: string): Glyph {
  return glyphs.get(ch) ?? glyphs.get(ch.toUpperCase()) ?? glyphs.get('?')!;
}

// Width in font pixels (1px gap between glyphs, none after the last).
export function measure(str: string): number {
  let w = 0;
  for (const ch of str) w += glyph(ch).w + 1;
  return Math.max(0, w - 1);
}
