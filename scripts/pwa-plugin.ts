import type { Plugin } from 'vite';
import { deflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';

// Vite plugin that makes the build an installable, offline PWA without any
// asset files in the repo: the icons are drawn from code (the player cube),
// encoded as PNG here, and the service worker precaches the exact build output.
//
// Dev server: serves the manifest and icons (no service worker in dev).

const BG: RGB = [0x12, 0x0a, 0x24];
const THEME = '#0a0a0a';

type RGB = [number, number, number];
const hex = (h: string): RGB => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)];

// 9×9 art grid of the player cube with its normal face (see drawPlayer).
function cubeColor(col: number, row: number): RGB | null {
  const face = [[2, 3], [5, 3], [2, 6], [3, 7], [4, 7], [5, 7], [6, 6]];
  if (face.some(([c, r]) => c === col && r === row)) return hex('#1a0a2e');
  if (row < 1 || row > 7 || col < 1 || col > 7) return null;
  if (row === 7 || col === 7) return hex('#7c3aed');
  if (row === 1 || col === 1) return hex('#e9d5ff');
  return hex('#c084fc');
}

// The cube spans ~60% of the icon, inside the maskable safe zone (80%).
function drawIcon(size: number): Uint8Array {
  const px = new Uint8Array(size * size * 3);
  const cell = Math.floor(size * 0.6 / 9);
  const off = Math.floor((size - cell * 9) / 2);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const col = Math.floor((x - off) / cell), row = Math.floor((y - off) / cell);
      const inside = x >= off && y >= off && col < 9 && row < 9;
      const c = (inside && cubeColor(col, row)) || BG;
      px.set(c, (y * size + x) * 3);
    }
  }
  return px;
}

// ----- minimal PNG encoder (8-bit RGB, no filtering) -----
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}
function encodePng(size: number, rgb: Uint8Array): Buffer {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0); ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; ihdr[9] = 2; // 8-bit, truecolor RGB
  const raw = Buffer.alloc((size * 3 + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size * 3 + 1)] = 0; // filter: none
    Buffer.from(rgb.buffer, y * size * 3, size * 3).copy(raw, y * (size * 3 + 1) + 1);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const ICONS: Record<string, number> = {
  'icons/icon-192.png': 192,
  'icons/icon-512.png': 512,
  'icons/icon-maskable-512.png': 512,
  'icons/apple-touch-icon.png': 180,
};

const MANIFEST = {
  name: 'Escapa Escapa',
  short_name: 'Escapa',
  description: 'Pixel-art auto-runner: dodge obstacles across three lanes and reach the goal.',
  lang: 'es',
  start_url: './',
  scope: './',
  display: 'fullscreen',
  display_override: ['fullscreen', 'standalone'],
  orientation: 'any',
  background_color: THEME,
  theme_color: THEME,
  categories: ['games'],
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};

// Network-first for page loads (so updates arrive), cache-first for the
// hashed assets; old caches are dropped when a new version activates.
function serviceWorker(version: string, assets: string[]): string {
  return `// Generated by scripts/pwa-plugin.ts — do not edit.
const CACHE = 'escapa-${version}';
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req)));
});
`;
}

export function pwa(): Plugin {
  const pngs = new Map(Object.entries(ICONS).map(([file, size]) => [file, encodePng(size, drawIcon(size))]));
  const manifest = JSON.stringify(MANIFEST, null, 2);

  return {
    name: 'escapa-pwa',
    enforce: 'post', // run generateBundle after index.html is in the bundle

    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = (req.url ?? '').split('?')[0].replace(/^\//, '');
        if (path === 'manifest.webmanifest') {
          res.setHeader('Content-Type', 'application/manifest+json');
          res.end(manifest);
        } else if (pngs.has(path)) {
          res.setHeader('Content-Type', 'image/png');
          res.end(pngs.get(path));
        } else {
          next();
        }
      });
    },

    generateBundle(_, bundle) {
      for (const [fileName, source] of pngs) this.emitFile({ type: 'asset', fileName, source });
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: manifest });

      const files = [...new Set([...Object.keys(bundle), 'index.html', ...pngs.keys(), 'manifest.webmanifest'])];
      const hash = createHash('sha256');
      for (const item of Object.values(bundle)) hash.update(item.type === 'chunk' ? item.code : item.source);
      hash.update(manifest);
      const version = hash.digest('hex').slice(0, 12);
      const assets = ['./', ...files.map(f => './' + f)];
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, assets) });
    },
  };
}
